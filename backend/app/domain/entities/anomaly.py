"""Domain entity representing predictive fraud and payroll anomalies."""

from dataclasses import dataclass
from enum import Enum
from typing import Optional


class RiskSeverity(str, Enum):
    """Classification of the operational and financial risk level."""

    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class AnomalyCategory(str, Enum):
    """Category of payroll inconsistency detected by the ML engine."""

    OVERTIME_SPIKE = "OVERTIME_SPIKE"
    GHOST_EMPLOYEE = "GHOST_EMPLOYEE"
    DUPLICATE_PAYMENT = "DUPLICATE_PAYMENT"
    SUBSTITUTION_MISMATCH = "SUBSTITUTION_MISMATCH"
    VACATION_OVERLAP = "VACATION_OVERLAP"
    SUSPICIOUS_ADDITIONAL = "SUSPICIOUS_ADDITIONAL"


@dataclass
class Anomaly:
    """Represents a flagged risk item produced by the PayTrust Machine Learning engine.

    Attributes:
        id: Unique anomaly finding identifier.
        paystub_id: Identifier of the associated paystub under review.
        employee_id: Identifier of the employee involved.
        category: Classified category of the anomaly.
        severity: Risk severity ranking (LOW, MEDIUM, HIGH, CRITICAL).
        paytrust_score: Calculated risk score between 0 and 100, where 100 is highest fraud probability.
        explanation: Natural language explanation generated by the compliance agent for the DP.
        suggested_action: Recommended remediation step (e.g., Hold payment, Request timecard audit).
        is_resolved: True if a human HR/DP analyst reviewed and resolved the alert.
        resolution_notes: Human reviewer notes explaining the override or confirmation.
    """

    id: str
    paystub_id: str
    employee_id: str
    category: AnomalyCategory
    severity: RiskSeverity
    paytrust_score: float
    explanation: str
    suggested_action: str
    is_resolved: bool = False
    resolution_notes: Optional[str] = None
